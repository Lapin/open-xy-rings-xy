#!/usr/bin/env python3
"""Generates tables.h: the fixed-point lookup tables the resonator reads.

The stiffness and damping curves follow Mutable Instruments Rings
(rings/resources/lookup_tables.py, MIT, Emilie Gillet). Run from the machine
folder: python3 tools/gen_tables.py > tables.h
"""
import math

Q31 = 2 ** 31
N = 256


def q(value, bits, limit=2 ** 31 - 1):
    word = int(round(value * (1 << bits)))
    return max(-limit - 1, min(limit, word))


def emit(name, words, note):
    print('// ' + note)
    print('const opxy::i32 %s[%d] = {' % (name, len(words)))
    for i in range(0, len(words), 8):
        print('    ' + ', '.join(str(w) for w in words[i:i + 8]) + ',')
    print('};')
    print()


print('#pragma once')
print('// Generated by tools/gen_tables.py; do not edit by hand.')
print('#include <opxy/types.hpp>')
print()
print('namespace mi_rings {')

# Quarter sine: sin(pi/2 * i / 256), Q31. sin(pi f) for f in [0, 0.5] reads
# index 512 f; cosines read it through quadrant folding.
emit('kSine', [q(math.sin(math.pi / 2 * i / N), 31) for i in range(N + 1)],
     'sin(pi/2 * i/256), Q31')

# Rings' stiffness curve over Structure, -0.0625 .. 2, Q27.
stiffness = []
for i in range(N + 1):
    g = i / N
    if g < 0.25:
        s = -(0.25 - g) * 0.25
    elif g < 0.3:
        s = 0.0
    elif g < 0.9:
        s = 0.01 * 10 ** ((g - 0.3) / 0.6 * 2.005) - 0.01
    else:
        g2 = ((g - 0.9) / 0.1) ** 2
        s = 1.5 - math.cos(g2 * math.pi) / 2
    stiffness.append(s)
stiffness[-1] = stiffness[-2] = 2.0
emit('kStiffness', [q(s, 27) for s in stiffness],
     'Rings stiffness over Structure, Q27')

# Rings' damping curve: q = 500 * 10^(4 damping), 500 .. 5,000,000, Q8.
emit('kQuality', [q(500 * 10 ** (4 * i / N), 8) for i in range(N + 1)],
     '500 * 10^(4 * i/256), Q8')

# 2^(i/64) for i in 0..64, Q30: fractional octaves.
emit('kExp2', [q(2 ** (i / 64), 30) for i in range(65)],
     '2^(i/64), Q30')
print('}')
